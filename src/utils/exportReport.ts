import { PaperAnalysis, PaperMetadata } from '../types/research';

export function generateTextReport(analysis: PaperAnalysis, metadata?: PaperMetadata): string {
  const divider = '='.repeat(76);
  const subDivider = '-'.repeat(76);

  const lines: string[] = [
    divider,
    'RESEARCHMATE – ACADEMIC RESEARCH PAPER ANALYSIS REPORT',
    divider,
    `Title:      ${analysis.title}`,
    `Field:      ${analysis.field}`,
    analysis.authors ? `Authors:    ${analysis.authors}` : '',
    analysis.year ? `Year/Date:  ${analysis.year}` : '',
    metadata ? `Source:     ${metadata.filename} (${metadata.pageCount} pages, ~${metadata.wordCount} words)` : '',
    `Generated:  ${new Date().toLocaleString()}`,
    divider,
    '',
    '1. EXECUTIVE RESEARCH SUMMARY',
    subDivider,
    analysis.summary,
    '',
    '2. RESEARCH PROBLEM & SIGNIFICANCE',
    subDivider,
    analysis.researchProblem,
    '',
    '3. RESEARCH OBJECTIVES & HYPOTHESES',
    subDivider,
    ...(analysis.researchObjectives || []).map((obj, i) => `  [${i + 1}] ${obj}`),
    '',
    '4. METHODOLOGY & EXPERIMENTAL FRAMEWORK',
    subDivider,
    'Overview:',
    `  ${analysis.methodology.overview}`,
    '',
    'Data / Materials & Cohort:',
    `  ${analysis.methodology.datasetOrMaterials}`,
    '',
    'System Architecture / Model Setup:',
    `  ${analysis.methodology.systemArchitecture}`,
    '',
    'Evaluation Metrics & Controls:',
    `  ${analysis.methodology.evaluationMetrics}`,
    '',
    'Step-by-Step Methodology Workflow:',
    ...(analysis.methodology.workflowSteps || []).map(
      (s) => `  Step ${s.stepNumber}: ${s.title}\n    ${s.description}`
    ),
    '',
    '5. KEY FINDINGS & EMPIRICAL RESULTS',
    subDivider,
    ...(analysis.keyFindings || []).map(
      (kf, i) => `  [${i + 1}] ${kf.headline}\n      ${kf.detail}`
    ),
    '',
    '6. RESEARCH LIMITATIONS & THREATS TO VALIDITY',
    subDivider,
    ...(analysis.limitations || []).map(
      (lim, i) => `  [${i + 1}] [${lim.category}] ${lim.description}`
    ),
    '',
    '7. FUTURE RESEARCH SCOPE & EXTENSIONS',
    subDivider,
    ...(analysis.futureResearchScope || []).map(
      (fut, i) => `  [${i + 1}] Direction: ${fut.area}\n      Recommendation: ${fut.recommendation}`
    ),
    '',
  ];

  if (analysis.glossary && analysis.glossary.length > 0) {
    lines.push(
      '8. KEY CONCEPTS & TERMINOLOGY GLOSSARY',
      subDivider,
      ...analysis.glossary.map((g) => `  * ${g.term}:\n      ${g.definition}`),
      ''
    );
  }

  lines.push(
    divider,
    'End of Report – Generated by ResearchMate (Powered by Google Gemini AI)',
    divider
  );

  return lines.filter((l) => l !== undefined).join('\n');
}

export function downloadTextFile(filename: string, content: string): void {
  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function downloadMarkdownFile(filename: string, analysis: PaperAnalysis, metadata?: PaperMetadata): void {
  const mdLines: string[] = [
    `# ${analysis.title}`,
    `**Field:** ${analysis.field} | **Authors:** ${analysis.authors || 'N/A'} | **Year:** ${analysis.year || 'N/A'}`,
    metadata ? `**File:** ${metadata.filename} (${metadata.pageCount} pages, ~${metadata.wordCount} words)\n` : '',
    '## 1. Executive Summary',
    analysis.summary,
    '\n## 2. Research Problem',
    analysis.researchProblem,
    '\n## 3. Research Objectives',
    ...(analysis.researchObjectives || []).map((o, i) => `${i + 1}. ${o}`),
    '\n## 4. Methodology',
    `**Overview:** ${analysis.methodology.overview}\n`,
    `**Data / Materials:** ${analysis.methodology.datasetOrMaterials}\n`,
    `**System Architecture:** ${analysis.methodology.systemArchitecture}\n`,
    `**Evaluation Metrics:** ${analysis.methodology.evaluationMetrics}\n`,
    '### Workflow Steps',
    ...(analysis.methodology.workflowSteps || []).map(s => `${s.stepNumber}. **${s.title}**: ${s.description}`),
    '\n## 5. Key Findings',
    ...(analysis.keyFindings || []).map((kf, i) => `${i + 1}. **${kf.headline}**\n   ${kf.detail}`),
    '\n## 6. Limitations',
    ...(analysis.limitations || []).map((lim, i) => `${i + 1}. **[${lim.category}]** ${lim.description}`),
    '\n## 7. Future Research Scope',
    ...(analysis.futureResearchScope || []).map((fut, i) => `${i + 1}. **${fut.area}**: ${fut.recommendation}`),
  ];

  if (analysis.glossary?.length) {
    mdLines.push('\n## 8. Key Concepts & Glossary');
    analysis.glossary.forEach(g => {
      mdLines.push(`- **${g.term}**: ${g.definition}`);
    });
  }

  const blob = new Blob([mdLines.join('\n')], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
